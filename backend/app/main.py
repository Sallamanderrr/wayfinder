"""HTTP API: a streaming chat endpoint (Server-Sent Events) plus history and health checks.

Run with:  uvicorn app.main:app --reload --port 8000
"""

from __future__ import annotations

import json
import logging
from collections.abc import Iterator
from contextlib import asynccontextmanager
from typing import Any

from fastapi import FastAPI, Request
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import StreamingResponse
from pydantic import BaseModel, Field

from .assistant import TravelAssistant, build_assistant
from .config import get_settings

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger("wayfinder")


class ChatRequest(BaseModel):
    thread_id: str = Field(min_length=1, max_length=64, description="Conversation id, generated by the client.")
    message: str = Field(min_length=1, max_length=4000)


def create_app(assistant: TravelAssistant | None = None) -> FastAPI:
    """App factory; tests inject an assistant built on a fake LLM."""
    settings = get_settings()

    @asynccontextmanager
    async def lifespan(app: FastAPI):
        if assistant is not None:
            app.state.assistant = assistant
        else:
            app.state.assistant = build_assistant(settings)
            logger.info("Wayfinder ready (model: %s)", settings.llm_model)
        yield

    app = FastAPI(title="Wayfinder API", lifespan=lifespan)
    app.add_middleware(
        CORSMiddleware, allow_origins=settings.cors_origins, allow_methods=["*"], allow_headers=["*"]
    )

    @app.get("/api/health")
    def health() -> dict[str, str]:
        return {"status": "ok"}

    @app.post("/api/chat")
    def chat(body: ChatRequest, request: Request) -> StreamingResponse:
        bot: TravelAssistant = request.app.state.assistant

        def events() -> Iterator[str]:
            # A sync generator: Starlette iterates it in a worker thread, so the
            # blocking LLM and HTTP calls never stall the event loop.
            try:
                for event in bot.stream_turn(body.thread_id, body.message):
                    yield _sse(event)
            except Exception as exc:  # report, don't drop the stream silently
                logger.exception("Chat turn failed")
                yield _sse(
                    {
                        "type": "error",
                        "message": f"The assistant hit an error ({type(exc).__name__}). "
                        "Check the backend logs for details.",
                    }
                )

        return StreamingResponse(
            events(),
            media_type="text/event-stream",
            headers={"Cache-Control": "no-cache", "X-Accel-Buffering": "no"},
        )

    @app.get("/api/threads/{thread_id}")
    def history(thread_id: str, request: Request) -> dict[str, Any]:
        return {"thread_id": thread_id, "messages": request.app.state.assistant.history(thread_id)}

    return app


def _sse(event: dict[str, Any]) -> str:
    return f"data: {json.dumps(event, ensure_ascii=False)}\n\n"


app = create_app()
